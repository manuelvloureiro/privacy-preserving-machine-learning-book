"""code/part05-synthetic-data/opendp_evaluating_synthetic_data.py runs and prints what the OpenDP book's chapter on
evaluating synthetic data quotes.

The deterministic lines (the versions, the unit and the budget, the scales, thresholds and conversions to epsilon of
every release, the facts about the data, the real-data classifier, the statement) are checked exactly. OpenDP's noise
cannot be seeded, so the releases are checked against the bounds the page states and justifies:

- every one-way and every measured marginal of the fitted model has a total variation distance under 3 k std / (2 n),
  three of the table's own standard deviations in every one of its k cells at once;
- the four-way table, which AIM never measures, is further from the truth than the best measured marginal, and the
  table refuses to give it a standard deviation;
- the classifier trained on synthetic rows scores within one percentage point of the one trained on real rows;
- the one-way marginals at rho = 0.5 are on average no further from the truth than at rho = 0.02, whose scales are
  five times larger;
- MST, which measures only pairs, misses the four-way table by more than AIM at the same budget;
- rows drawn by sampling are further from the truth than the model they are drawn from.
"""

import re
import subprocess
import sys
from pathlib import Path

import pytest

SCRIPT = (
    Path(__file__).resolve().parent.parent / "code" / "part05-synthetic-data" / "opendp_evaluating_synthetic_data.py"
)

COLUMNS = ("SEX", "AGE", "HWUSUAL", "ILOSTAT")

DETERMINISTIC = [
    "opendp version: 0.16.0  mbi version: 1.1.0",
    "privacy unit: (SymmetricDistance(), 36)",
    "privacy loss: (Approximate(ZeroConcentratedDivergence), (0.1, 1e-07))",
    (
        "aim rho=0.1: oneway scale=227.6840 threshold=1364  scale of a round's marginal=379.4733  "
        "epsilon at delta=1e-07: 2.3484"
    ),
    "rows: 3,811,932  keys ILOSTAT: [1, 2, 3, 9, None]",
    "four-way cells: 240  measured by AIM: False",
    "std of the four-way table: attrs (('SEX', 'AGE', 'HWUSUAL', 'ILOSTAT')) are not covered by the query set",
    "cells of the share with at least 1,000 real rows: 26",
    "held-out real rows: 200,000  real training rows: 200,000  synthetic training rows: 200,000",
    "features: 11 indicators",
    "share working in the held-out rows: 0.3976",
    "train on real, test on real: accuracy=0.9313",
    "standard error of an accuracy on 200,000 rows: 0.0006",
    (
        "aim rho=0.02: oneway scale=509.1169 threshold=3004  scale of a round's marginal=848.5281  "
        "epsilon at delta=1e-07: 0.9951"
    ),
    (
        "aim rho=0.5: oneway scale=101.8234 threshold=630  scale of a round's marginal=169.7056  "
        "epsilon at delta=1e-07: 5.6709"
    ),
    "mst rho=0.1: oneway scale=227.6840 threshold=1364  scale of a pair=207.8461  epsilon at delta=1e-07: 2.3484",
    "budget the four contexts add up to if all were released from the same data: rho=0.72",
    (
        "This synthetic dataset of 200,000 rows was generated by AIM (OpenDP 0.16.0, mbi 1.1.0, rounds=10, queries up "
        "to 3 columns) from one contingency table over SEX, AGE, HWUSUAL, ILOSTAT released under (rho = 0.1, "
        "delta = 1e-07)-zero-concentrated differential privacy, which is (epsilon = 2.35, delta = 2e-07)-differential "
        "privacy, for adding or removing all of one person's survey responses, at most 36 of them, under the central "
        "model. The keys of SEX and the cuts of AGE and HWUSUAL were fixed in advance; nulls were recoded to "
        "{'AGE': 0.0, 'HWUSUAL': 99.0}; the keys of ILOSTAT were released with a threshold of 1364. Drawing the rows "
        "by independent sampling is post-processing and spent nothing."
    ),
]

NUMBER = r"([-+]?[\d,]+(?:\.\d+)?)"


def numbers(pattern: str, out: str) -> list[float]:
    m = re.search(pattern, out, re.MULTILINE)
    assert m, f"no line matches {pattern!r}"
    return [float(g.replace(",", "")) for g in m.groups()]


def distances(name: str, kind: str, out: str) -> dict[str, tuple[float, float]]:
    """The marginal label mapped to (total variation distance, bound) for one release and kind of line."""
    pattern = rf"^{kind} (.+?) \({name}\): tv=([\d.]+) largest cell error=[\d,]+ rows  std=[\d.]+ bound=([\d.]+)$"
    found = {label: (float(tv), float(bound)) for label, tv, bound in re.findall(pattern, out, re.MULTILINE)}
    assert found, f"no {kind} lines printed for {name}"
    return found


def tuning(name: str, out: str) -> dict[str, float]:
    pattern = (
        rf"^tuning \({name}, one run\): release {NUMBER} s  cliques={NUMBER}  one-way mean tv={NUMBER}"
        rf"  worst measured tv={NUMBER}  four-way tv={NUMBER}  share error={NUMBER} points"
        rf"  accuracy={NUMBER}  gap={NUMBER}  probability difference={NUMBER}$"
    )
    keys = ("seconds", "cliques", "oneway", "worst", "four", "share", "accuracy", "gap", "probability")
    return dict(zip(keys, numbers(pattern, out), strict=True))


def methods(name: str, label: str, out: str) -> tuple[float, float, float]:
    model, rounded, sampled = numbers(
        rf"^{name} {re.escape(label)} \(one run\): model={NUMBER}  round={NUMBER}  sample={NUMBER}$", out
    )
    return model, rounded, sampled


@pytest.fixture(scope="module")
def out() -> str:
    return subprocess.run([sys.executable, str(SCRIPT)], capture_output=True, text=True, check=True).stdout


@pytest.mark.libs
def test_deterministic_lines(out: str) -> None:
    lines = out.splitlines()
    for expected in DETERMINISTIC:
        assert expected in lines, f"missing line: {expected}"


@pytest.mark.libs
def test_measured_marginals_within_their_bound(out: str) -> None:
    oneway = distances("aim rho=0.1", "one-way", out)
    assert set(oneway) == set(COLUMNS)
    measured = distances("aim rho=0.1", "measured", out)
    assert measured
    for label, (tv, bound) in {**oneway, **measured}.items():
        assert tv < bound, (label, tv, bound)


@pytest.mark.libs
def test_unmeasured_query_is_worse_than_the_best_measured(out: str) -> None:
    four, best, worst = numbers(
        rf"^four-way \(aim rho=0\.1, one run\): tv={NUMBER} largest cell error=[\d,]+ rows"
        rf"  best measured .+ tv={NUMBER}  worst measured tv={NUMBER}$",
        out,
    )
    assert best <= worst
    assert four > best, (four, best)
    error, real, model = numbers(
        rf"^share working by SEX, AGE, HWUSUAL \(aim rho=0\.1, one run\): largest error={NUMBER} points at .+"
        rf"  real={NUMBER}%  model={NUMBER}%$",
        out,
    )
    assert abs(error - abs(real - model)) < 0.02 and 0 <= error <= 100


@pytest.mark.libs
def test_train_on_synthetic_test_on_real(out: str) -> None:
    accuracy, gap, probability = numbers(
        rf"^train on synthetic \(aim rho=0\.1, one run\), test on real: accuracy={NUMBER}  gap={NUMBER}"
        rf"  mean probability difference={NUMBER}$",
        out,
    )
    assert abs(gap) <= 0.01, gap  # one percentage point, against a standard error of 0.0006
    assert abs(0.9313 - gap - accuracy) < 1e-3
    assert 0 <= probability < 0.05


@pytest.mark.libs
def test_tuning(out: str) -> None:
    low, main, high, mst = (tuning(name, out) for name in ("aim rho=0.02", "aim rho=0.1", "aim rho=0.5", "mst rho=0.1"))
    # The one-way scale at rho = 0.02 is five times the scale at rho = 0.5, so its marginals are further off.
    assert high["oneway"] <= low["oneway"], (high, low)
    assert mst["cliques"] == 3
    assert mst["four"] > main["four"], (mst, main)  # pairs alone leave the triples to the model's assumptions
    for row in (low, main, high, mst):
        assert abs(row["gap"]) <= 0.02, row


@pytest.mark.libs
def test_rows_and_methods(out: str) -> None:
    for column in COLUMNS:
        at_rows, at_real = numbers(
            rf"^sampling noise on one-way {column}: expected tv at 200,000 rows={NUMBER}  at 3,811,932 rows={NUMBER}$",
            out,
        )
        assert at_real < at_rows
    model, rounded, sampled = methods("aim rho=0.1", "one-way tv summed", out)
    assert sampled > model and sampled > rounded, (model, rounded, sampled)
    # MST draws its leaves from the same parent; in mbi 1.1.0 rounding then couples them and moves the pair it
    # couples furthest from the model's marginal, which independent sampling does not.
    m = re.search(r"^mst rho=0\.1 (pair \(.+\) tv) \(one run\)", out, re.MULTILINE)
    assert m
    model, rounded, sampled = methods("mst rho=0.1", m.group(1), out)
    assert rounded >= model, (model, rounded, sampled)
